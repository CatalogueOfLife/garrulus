package org.catalogueoflife.nametracker.eval.modeb;

import org.catalogueoflife.nametracker.finder.api.Block;
import org.catalogueoflife.nametracker.finder.api.BlockType;
import org.catalogueoflife.nametracker.finder.api.Document;
import org.catalogueoflife.nametracker.finder.doc.TeiConverter;
import org.junit.jupiter.api.Test;
import org.testcontainers.containers.GenericContainer;
import org.testcontainers.containers.wait.strategy.Wait;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;
import org.testcontainers.utility.DockerImageName;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.net.URI;
import java.net.http.HttpClient;
import java.nio.charset.StandardCharsets;
import java.time.Duration;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Runs a small PDF through the real GROBID image. The image is 1.2 GB and needs a few GB of memory, so this test only
 * runs with the Maven profile {@code grobid}: {@code mvn -B -pl eval -am verify -Pgrobid -Dit.test=GrobidIT}.
 *
 * <p>Fixture {@code grobid/carabus-note.pdf}: a one-page PDF generated by {@code grobid/make-fixture.py} (next to it)
 * from text written for this test; it holds no third-party content and is dedicated to the public domain (CC0).
 */
@Testcontainers
class GrobidIT {
  @Container
  static final GenericContainer<?> GROBID = new GenericContainer<>(DockerImageName.parse("grobid/grobid:0.9.1-crf"))
      .withExposedPorts(8070)
      .waitingFor(Wait.forHttp("/api/isalive").forStatusCode(200).withStartupTimeout(Duration.ofMinutes(5)));

  private static byte[] fixture() throws IOException {
    try (InputStream in = GrobidIT.class.getResourceAsStream("/grobid/carabus-note.pdf")) {
      if (in == null) throw new IllegalStateException("Missing test resource /grobid/carabus-note.pdf");
      return in.readAllBytes();
    }
  }

  @Test
  void aSmallPdfGivesTeiWithParagraphsAndNoItalics() throws Exception {
    GrobidClient client = new GrobidClient(URI.create("http://" + GROBID.getHost() + ":" + GROBID.getMappedPort(8070)),
        HttpClient.newHttpClient());
    String tei = client.processFulltext(fixture());

    assertThat(tei).contains("<TEI").contains("<p>");
    // GROBID has no italics in its TEI (ADR-0002)
    assertThat(tei).doesNotContain("rend=\"italic\"");

    Document d = new TeiConverter().convert(new ByteArrayInputStream(tei.getBytes(StandardCharsets.UTF_8)), "fixture", w -> false);
    assertThat(d.blocks()).filteredOn(b -> b.type() == BlockType.PARAGRAPH).isNotEmpty();
    assertThat(d.blocks()).filteredOn(b -> b.type() == BlockType.TITLE).extracting(Block::text)
        .containsExactly("A new ground beetle of the genus Carabus (Coleoptera: Carabidae)");
    assertThat(d.blocks()).anyMatch(b -> b.text().contains("Pterostichus niger and Abax parallelepipedus"));
    assertThat(d.blocks()).allMatch(b -> b.styles().isEmpty());
  }
}
